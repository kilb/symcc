#!/usr/bin/env python3
"""Run one auditable, interleaved QA3 coverage-attribution campaign."""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import shutil
import sys
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "benchmark" / "qa3_repro"))

from qa3_common import (  # noqa: E402
    MeasurementError,
    StreamingCoverageOracle,
    coverage_status_is_eligible,
    iter_output_files,
    measure_corpus_interleaved,
    sha256_file,
    strategy_tag,
)


def _positive_int(value: str) -> int:
    parsed = int(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("value must be positive")
    return parsed


def _nonnegative_int(value: str) -> int:
    parsed = int(value)
    if parsed < 0:
        raise argparse.ArgumentTypeError("value must not be negative")
    return parsed


def _relative_label(path: Path, corpus: Path) -> str:
    try:
        return path.relative_to(corpus).as_posix()
    except ValueError:
        return path.name


def _write_json(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=True, indent=2, sort_keys=True) + "\n",
        encoding="ascii",
    )


def _write_manifest(directory: Path) -> None:
    rows = [
        f"{sha256_file(path)}  {path.relative_to(directory).as_posix()}"
        for path in sorted(directory.rglob("*"))
        if path.is_file() and path.name != "SHA256SUMS.txt"
    ]
    (directory / "SHA256SUMS.txt").write_text(
        "\n".join(rows) + "\n", encoding="ascii"
    )


def _write_readme(
    path: Path, summary: dict[str, Any], args: argparse.Namespace
) -> None:
    strategy_rows = [
        f"- `{name}`: {values['outputs']} outputs, "
        f"{values['normal_outputs']} normal, "
        f"{values['excluded_terminal_outputs']} terminal-excluded, "
        f"{values['outputs_with_seed_novel_edges']} landing hits, "
        f"{values['novel_edge_union']} seed-novel edges."
        for name, values in sorted(summary["strategies"].items())
    ]
    lines = [
        "# QA3 ABI-aligned coverage-oracle evidence",
        "",
        "This directory is generated by `benchmark/run_qa3_coverage_campaign.py`.",
        "It contains the selected and per-round edge sets needed to recompute",
        "the summary without trusting terminal output.",
        "",
        "## Protocol",
        "",
        f"- Rounds: {summary['rounds']}",
        f"- Inter-round delay: {summary['round_delay_ms']} ms",
        f"- Stability policy: `{summary['stability_policy']}`",
        f"- Input mode: `{summary['input_mode']}`",
        f"- Terminal status policy: `{summary['terminal_status_policy']}`",
        f"- Campaign observations: {summary['campaign_observations']}",
        f"- Compatibility-probe observations: "
        f"{summary['compatibility_probe_observations']}",
        f"- Oracle mode: `{summary['oracle_mode']}` "
        f"({summary['oracle_fallbacks']} fallback)",
        "",
        "## Observed result",
        "",
        f"- Baseline intersection/union: "
        f"{summary['baseline_intersection_edges']}/"
        f"{summary['baseline_union_edges']} edges.",
        f"- Strict stability passed: `{summary['strict_stability_passed']}`.",
        f"- Unstable inputs/events: {summary['unstable_input_count']}/"
        f"{summary['unstable_edge_events']}.",
        *strategy_rows,
        "",
        "The bundled corpus has only the `nominal` label. These numbers validate",
        "the coverage oracle and do not establish a solver-strategy speedup.",
        "",
        "## Files",
        "",
        "- `raw-campaign.json`: round order, every per-input replica edge set,",
        "  and the selected intersection.",
        "- `summary.json`: derived stability, landing, and complementarity metrics.",
        "- `SHA256SUMS.txt`: content manifest for all evidence files.",
        "",
        "## Reproduction parameters",
        "",
        f"- AFL binary: `{args.afl_binary}`",
        f"- Corpus: `{args.corpus}`",
        f"- Seed: `{args.seed}`",
        f"- afl-showmap: `{args.showmap_binary}`",
        "",
    ]
    path.write_text("\n".join(lines), encoding="ascii")


def run(args: argparse.Namespace) -> dict[str, Any]:
    afl_binary = args.afl_binary.resolve()
    corpus = args.corpus.resolve()
    seed = args.seed.resolve()
    output = args.output.resolve()
    showmap_candidate = shutil.which(args.showmap_binary)
    if showmap_candidate is None:
        raise MeasurementError(
            f"afl-showmap binary does not exist: {args.showmap_binary}"
        )
    showmap_binary = Path(showmap_candidate).resolve()
    if not afl_binary.is_file():
        raise MeasurementError(f"AFL binary does not exist: {afl_binary}")
    if not corpus.is_dir():
        raise MeasurementError(f"corpus directory does not exist: {corpus}")
    if not seed.is_file():
        raise MeasurementError(f"seed does not exist: {seed}")
    if output.exists():
        if not output.is_dir():
            raise MeasurementError(f"output path is not a directory: {output}")
        if any(output.iterdir()):
            raise MeasurementError(f"output directory is not empty: {output}")
    if not args.default_strategy or any(
        byte.isspace() for byte in args.default_strategy
    ):
        raise MeasurementError("default strategy must be one nonempty token")
    output.mkdir(parents=True, exist_ok=True)

    # The baseline may live inside the corpus directory. It is measured once
    # for the shared reference set, never counted as a candidate output.
    candidates = [
        path for path in iter_output_files(corpus) if path.resolve() != seed
    ]
    if not candidates:
        raise MeasurementError("corpus contains no regular input files")
    with StreamingCoverageOracle(
        afl_binary,
        repeats=1,
        stability_policy="strict",
        timeout_ms=args.showmap_timeout_ms,
        showmap_binary=str(showmap_binary),
        input_mode=args.input_mode,
    ) as oracle:
        campaign = measure_corpus_interleaved(
            oracle,
            [seed, *candidates],
            rounds=args.rounds,
            stability_policy=args.stability_policy,
            round_delay_seconds=args.replica_delay_ms / 1000.0,
        )
        oracle_mode = oracle.mode
        oracle_fallbacks = oracle.fallbacks
        oracle_restarts = oracle.restart_count
        oracle_probe = oracle.probe
        oracle_probe_observations = oracle.probe_observations
        resolved_input_mode = oracle.input_mode

    seed_measurement = campaign.measurements[seed]
    coverage_status_is_eligible(
        seed_measurement.status,
        policy="normal-only",
        label=f"baseline {seed}",
    )
    base_edges = set(seed_measurement.edges)
    strategy_outputs: Counter[str] = Counter()
    strategy_normal_outputs: Counter[str] = Counter()
    strategy_hits: Counter[str] = Counter()
    strategy_edges: dict[str, set[int]] = defaultdict(set)
    strategy_statuses: dict[str, Counter[str]] = defaultdict(Counter)
    status_counts: Counter[str] = Counter()
    unstable_inputs = []

    raw_inputs: dict[str, Any] = {}
    label_owners: dict[str, Path] = {}
    for path, selected in sorted(
        campaign.measurements.items(), key=lambda item: str(item[0])
    ):
        label = _relative_label(path, corpus)
        owner = label_owners.get(label)
        if owner is not None and owner != path:
            raise MeasurementError(
                f"non-unique evidence label {label!r}: {owner} and {path}"
            )
        label_owners[label] = path
        replicas = campaign.samples[path]
        for sample in replicas:
            status_counts[sample.status] += sample.replicas
        if selected.unstable_edges:
            unstable_inputs.append({
                "input": label,
                "unstable_edges": selected.unstable_edges,
                "replica_edge_counts": [
                    len(sample.edges) for sample in replicas
                ],
            })
        raw_inputs[label] = {
            "input_sha256": sha256_file(path),
            "status": selected.status,
            "selected_edges": sorted(selected.edges),
            "selected_edge_count": len(selected.edges),
            "union_edge_count": selected.union_edges,
            "intersection_edge_count": selected.intersection_edges,
            "unstable_edges": selected.unstable_edges,
            "replicas": [
                {
                    "status": sample.status,
                    "edges": sorted(sample.edges),
                    "edge_count": len(sample.edges),
                }
                for sample in replicas
            ],
        }

    for candidate in candidates:
        measurement = campaign.measurements[candidate.resolve()]
        tag = strategy_tag(candidate.name, args.default_strategy)
        strategy_outputs[tag] += 1
        strategy_statuses[tag][measurement.status] += 1
        if not coverage_status_is_eligible(
            measurement.status,
            policy=args.terminal_status_policy,
            label=str(candidate),
        ):
            continue
        strategy_normal_outputs[tag] += 1
        novel = set(measurement.edges) - base_edges
        if novel:
            strategy_hits[tag] += 1
        strategy_edges[tag].update(novel)

    tags = sorted(strategy_outputs)
    strategy_summary: dict[str, Any] = {}
    for tag in tags:
        others = set().union(*(
            strategy_edges[other] for other in tags if other != tag
        )) if len(tags) > 1 else set()
        outputs = strategy_outputs[tag]
        normal_outputs = strategy_normal_outputs[tag]
        landing_rate = (
            strategy_hits[tag] * 1_000_000 // normal_outputs
            if normal_outputs
            else None
        )
        edges_per_output = (
            len(strategy_edges[tag]) * 1_000_000 // normal_outputs
            if normal_outputs
            else None
        )
        strategy_summary[tag] = {
            "outputs": outputs,
            "normal_outputs": normal_outputs,
            "excluded_terminal_outputs": outputs - normal_outputs,
            "terminal_outputs": {
                status: count
                for status, count in sorted(strategy_statuses[tag].items())
                if status != "ok"
            },
            "outputs_with_seed_novel_edges": strategy_hits[tag],
            "landing_rate_ppm": landing_rate,
            "landing_rate_denominator": "normal_outputs",
            "novel_edge_union": len(strategy_edges[tag]),
            "exclusive_novel_edges": len(strategy_edges[tag] - others),
            "novel_edges_per_output_ppm": edges_per_output,
        }

    raw = {
        "schema": "symcc-qa3-interleaved-coverage-campaign-v2",
        "afl_binary": str(afl_binary),
        "afl_binary_sha256": sha256_file(afl_binary),
        "showmap_binary": str(showmap_binary),
        "showmap_binary_sha256": sha256_file(showmap_binary),
        "seed": _relative_label(seed, corpus),
        "seed_sha256": sha256_file(seed),
        "corpus": str(corpus),
        "rounds": args.rounds,
        "round_delay_ms": args.replica_delay_ms,
        "stability_policy": args.stability_policy,
        "input_mode": resolved_input_mode,
        "terminal_status_policy": args.terminal_status_policy,
        "showmap_timeout_ms": args.showmap_timeout_ms,
        "round_orderings": [
            [_relative_label(path, corpus) for path in ordering]
            for ordering in campaign.orderings
        ],
        "inputs": raw_inputs,
    }
    summary = {
        "schema": "symcc-qa3-interleaved-coverage-summary-v2",
        "afl_binary_sha256": raw["afl_binary_sha256"],
        "showmap_binary_sha256": raw["showmap_binary_sha256"],
        "seed_sha256": raw["seed_sha256"],
        "candidate_inputs": len(candidates),
        "unique_measured_inputs": len(campaign.measurements),
        "rounds": args.rounds,
        "campaign_observations": sum(status_counts.values()),
        "compatibility_probe_observations": oracle_probe_observations,
        "total_oracle_observations": (
            sum(status_counts.values()) + oracle_probe_observations
        ),
        "showmap_statuses": dict(sorted(status_counts.items())),
        "stability_policy": args.stability_policy,
        "input_mode": resolved_input_mode,
        "terminal_status_policy": args.terminal_status_policy,
        "baseline_status": seed_measurement.status,
        "round_delay_ms": args.replica_delay_ms,
        "strict_stability_passed": not unstable_inputs,
        "unstable_input_count": len(unstable_inputs),
        "unstable_edge_events": sum(
            item["unstable_edges"] for item in unstable_inputs
        ),
        "unstable_inputs": unstable_inputs,
        "oracle_mode": oracle_mode,
        "oracle_fallbacks": oracle_fallbacks,
        "oracle_restarts": oracle_restarts,
        "oracle_probe": oracle_probe,
        "baseline_selected_edges": len(seed_measurement.edges),
        "baseline_union_edges": seed_measurement.union_edges,
        "baseline_intersection_edges": seed_measurement.intersection_edges,
        "strategies": strategy_summary,
    }
    _write_json(output / "raw-campaign.json", raw)
    _write_json(output / "summary.json", summary)
    _write_readme(output / "README.md", summary, args)
    _write_manifest(output)
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--afl-binary", required=True, type=Path)
    parser.add_argument("--corpus", required=True, type=Path)
    parser.add_argument("--seed", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--rounds", type=_positive_int, default=3)
    parser.add_argument(
        "--stability-policy",
        choices=("strict", "intersection", "union"),
        default="strict",
    )
    parser.add_argument(
        "--replica-delay-ms", type=_nonnegative_int, default=1_000
    )
    parser.add_argument(
        "--showmap-timeout-ms", type=_positive_int, default=5_000
    )
    parser.add_argument("--showmap-binary", default="afl-showmap")
    parser.add_argument(
        "--input-mode", choices=("auto", "file", "stdin"), default="auto"
    )
    parser.add_argument(
        "--terminal-status-policy",
        choices=("normal-only", "stratified"),
        default="normal-only",
    )
    parser.add_argument("--default-strategy", default="nominal")
    args = parser.parse_args()
    try:
        summary = run(args)
    except MeasurementError as error:
        print(f"qa3 coverage campaign: {error}", file=sys.stderr)
        return 2
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
